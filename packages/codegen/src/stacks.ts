/** Import path from one app file to another (`./components/Button`). */
export function importPath(fromFile: string, toFile: string): string {
  const rel = posix.relative(posix.dirname(fromFile), toFile).replace(/\.tsx?$/, "");
  return rel.startsWith(".") ? rel : `./${rel}`;
}
