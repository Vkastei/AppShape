function packageJson(name: string, scripts: Record<string, string>, deps: Record<string, string>, dev: Record<string, string>): string {
  const sort = (o: Record<string, string>) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));
  // packageManager pins pnpm (corepack would otherwise fetch the newest major).
  return `${JSON.stringify({ name, private: true, version: "0.0.0", type: "module", packageManager: PNPM, scripts, dependencies: sort(deps), devDependencies: sort(dev) }, null, 2)}\n`;
}

/** npm-safe package name from a project name. */
export function packageName(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9-]+/g, "-").replace(/^-+|-+$/g, "") || "app";
}

