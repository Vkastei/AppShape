/** Import lines for Motion: the components (React Server Components need the client entry), and the rest. */
export function motionImports(layout: AppLayout): { components: string; module: string } {
  const pkg = layout.motion ?? "motion";
  const module = pkg === "motion" ? "motion/react" : "framer-motion";
  if (layout.stack === "next-app") return { components: `import * as motion from "${pkg === "motion" ? "motion/react-client" : "framer-motion/client"}";`, module };
  return { components: `import { motion } from "${module}";`, module };
}

