/**
 * Plays the entrances that wait for their element to scroll into view (CSS apps): marks each
 * `aps-reveal` element when it comes into view (`data-revealed`); `aps-reveal-repeat` ones again
 * each time. Until it runs (or with reduced motion) the elements simply show. Rendered once per page.
 */
export const SCROLL_REVEAL_MODULE = `"use client";

import { useEffect } from "react";

/** Plays the scroll-in animations of the page (generated by AppShape; see the theme's motion part). */
export function ScrollReveal() {
  useEffect(() => {
    const root = document.documentElement;
    const seen = new WeakSet<Element>();
    const observer = new IntersectionObserver(
      (entries) => {
        for (const entry of entries) {
          const element = entry.target as HTMLElement;
          if (entry.isIntersecting) element.dataset.revealed = "";
          else if (element.classList.contains("aps-reveal-repeat")) delete element.dataset.revealed;
        }
      },
      { rootMargin: "0px 0px -10% 0px" },
    );
    const watch = () => {
      for (const element of document.querySelectorAll<HTMLElement>(".aps-reveal, .aps-reveal-repeat")) {
        if (seen.has(element)) continue;
        seen.add(element);
        // already in view: keeps playing (it started with the page)
        if (element.getBoundingClientRect().top < window.innerHeight * 0.9) element.dataset.revealed = "";
        observer.observe(element);
      }
    };
    watch();
    root.dataset.reveal = "";
    const changes = new MutationObserver(watch);
    changes.observe(document.body, { childList: true, subtree: true });
    return () => {
      observer.disconnect();
      changes.disconnect();
      delete root.dataset.reveal;
    };
  }, []);
  return null;
}
`;

