function nextScaffold(appName: string, layout: AppLayout, router: "app" | "pages"): Record<string, string> {
  const b = base(layout);
  const files: Record<string, string> = {
    "package.json": packageJson(
      packageName(appName),
      { dev: "next dev", build: "next build", typecheck: "next typegen && tsc --noEmit" },
      { ...SHARED_DEPS, ...motionDeps(layout), next: "^16.3.8" },
      { ...SHARED_DEV, "@tailwindcss/postcss": "^4.3.3", "@types/node": "^24.4.0" },
    ),
    ".gitignore": GITIGNORE,
    "next.config.ts": NEXT_CONFIG,
    "postcss.config.mjs": POSTCSS,
    "tsconfig.json": NEXT_TSCONFIG,
    [`${b}lib/utils.ts`]: UTILS,
  };
  if (router === "app") {
    files[`${b}app/layout.tsx`] = `import type { Metadata } from "next";
import type { ReactNode } from "react";
import "./globals.css";

export const metadata: Metadata = {
  title: ${JSON.stringify(appName)},
};

export default function RootLayout({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <body>{children}</body>
    </html>
  );
}
`;
  } else {
    files[`${b}pages/_app.tsx`] = `import type { AppProps } from "next/app";
import "../styles/globals.css";

export default function App({ Component, pageProps }: AppProps) {
  return <Component {...pageProps} />;
}
`;
  }
  return files;
}

