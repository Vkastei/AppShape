function viteFiles(name: string, title: string, plugins: { imports: string[]; list: string[] }, main: string): Record<string, string> {
  return {
    ".gitignore": GITIGNORE,
    "index.html": INDEX_HTML(title),
    "tsconfig.json": VITE_TSCONFIG,
    "vite.config.ts": `${plugins.imports.join("\n")}
import { defineConfig } from "vite";

export default defineConfig({
  plugins: [${plugins.list.join(", ")}],
});
`,
    "src/main.tsx": main,
    "src/lib/utils.ts": UTILS,
  };
}

function pageBody(page: PageModule, exportLine: string): string {
  const imports = page.imports.length ? `${page.imports.join("\n")}\n\n` : "";
  const preamble = page.preamble ? `${page.preamble}\n\n` : "";
  return `${imports}${preamble}${exportLine} {
  return (
${page.jsx}
  );
}
`;
}

