/** The app frameworks code generation supports. */
export const STACK_IDS = ["vite-react-router", "next-app", "next-pages", "vite-tanstack"] as const;
export type StackId = (typeof STACK_IDS)[number];

/** What code generation needs to know about the target app. */
export interface AppLayout {
  stack: StackId;
  /** Next.js apps can keep `app/`, `pages/`, `components/` under `src/`. Vite apps always use `src/`. */
  srcDir: boolean;
  tailwind: 3 | 4;
  /** Existing CSS entry that imports Tailwind (relative to the app root), if not the stack default. */
  cssPath?: string;
  /** The app animates with Motion (`motion`, or its older name `framer-motion`): entrances are generated as Motion code. */
  motion?: "motion" | "framer-motion";
}

export interface PageModule {
  /** PascalCase screen name, e.g. `Pricing`. */
  name: string;
  route: string;
  /** Import lines (already formatted). */
  imports: string[];
  /** The page's JSX, indented for a `return (` at two levels. */
  jsx: string;
  /** Module code between the imports and the page function (Next.js `metadata`). */
  preamble?: string;
}

export interface Stack {
  id: StackId;
  label: string;
  pagePath(route: string, name: string, layout: AppLayout): string;
  componentPath(name: string, layout: AppLayout): string;
  utilsPath(layout: AppLayout): string;
  cssPath(layout: AppLayout): string;
  /** Import line for the router's link component (named `Link`). */
  linkImport: string;
  /** Attribute that takes the route (`to` or `href`). */
  linkAttr: "to" | "href";
  /** Route used when a link property has no target. */
  emptyTarget: string;
  /** Whether a link prop must be typed by the router (TanStack's typed routes). */
  linkPropType: string;
  linkPropImport?: string;
  /** Wraps a page's JSX into its module. */
  pageModule(page: PageModule): string;
  /** Routes file listing the pages (React Router); file-based routers have none. */
  routesPath?(layout: AppLayout): string;
  routesModule?(pages: { name: string; route: string; importPath: string }[]): string;
  /** Files of a new app (without pages, components, theme and routes). */
  scaffold(appName: string, layout: AppLayout): Record<string, string>;
}

