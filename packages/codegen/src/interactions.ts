import { type DesignNode, type Frame, type Interaction, type JsonValue, walk } from "@appshape/ir";

/**
 * Interactions as code without dependencies or client JavaScript: overlay screens are native
 * popovers (`popover` + `popoverTarget`: top layer, Esc and a click outside close them, focus goes
 * back to the button), scrolling to a section is a link to its id, disclosures are `<details>`.
 * Only switching a component's property (a tab) needs state: that component becomes a client
 * component with `useState`.
 */

/** The id of an overlay's popover element (`mobile-menu`). */
export function overlayId(frame: Pick<Frame, "name">): string {
  return frame.name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "") || "overlay";
}

/** Classes of an overlay's popover element: how it is shown (see the overlays CSS part) and its width. */
export function overlayClasses(interaction: Extract<Interaction, { type: "open" }>, frame: Frame): string[] {
  const width = frame.viewports[0]?.width;
  const kind = interaction.as === "drawer" ? ["aps-drawer", ...(interaction.side === "left" ? ["aps-drawer-left"] : [])] : [`aps-${interaction.as}`];
  return ["aps-overlay", ...kind, ...(width ? [`w-[${width}px]`] : []), ...(interaction.as === "dropdown" ? [`[position-anchor:--${overlayId(frame)}]`] : [])];
}

export const OVERLAYS_START = "/* appshape:overlays (menus, drawers and dialogs: native popovers) */";
export const OVERLAYS_END = "/* appshape:overlays end */";

/** The overlays part of the CSS block: how popovers are placed, their backdrop and entrance. */
export function overlaysPart(): string {
  return [
    OVERLAYS_START,
    ".aps-overlay { margin: 0; padding: 0; border: 0; color: inherit; background: transparent; max-width: calc(100vw - 2rem); overflow: auto; }",
    ".aps-overlay::backdrop { background: rgb(0 0 0 / 0.4); }",
    ".aps-modal { margin: auto; max-height: calc(100dvh - 2rem); }",
    ".aps-drawer { inset: 0 0 0 auto; height: 100dvh; max-height: none; max-width: 90vw; }",
    ".aps-drawer > * { min-height: 100%; }",
    ".aps-drawer-left { inset: 0 auto 0 0; }",
    ".aps-dropdown { inset: auto; position-area: bottom span-right; position-try-fallbacks: flip-block, flip-inline; margin-top: 0.5rem; }",
    ".aps-dropdown::backdrop { background: transparent; }",
    "@media (prefers-reduced-motion: no-preference) {",
    "  html { scroll-behavior: smooth; }",
    "  .aps-overlay { transition: opacity 0.2s, translate 0.25s ease-out, display 0.25s allow-discrete, overlay 0.25s allow-discrete; }",
    "  @starting-style {",
    "    .aps-modal:popover-open, .aps-dropdown:popover-open { opacity: 0; }",
    "    .aps-drawer:popover-open { translate: 100% 0; }",
    "    .aps-drawer-left:popover-open { translate: -100% 0; }",
    "  }",
    "}",
    OVERLAYS_END,
  ].join("\n");
}

/** Ids of the elements a screen scrolls to → their `id` attribute (`features`, `features-2`, …). */
export function scrollTargets(root: DesignNode): Map<string, string> {
  const wanted = new Set<string>();
  walk(root, (node) => {
    if (node.interaction?.type === "scroll") wanted.add(node.interaction.nodeId);
  });
  const ids = new Map<string, string>();
  const taken = new Set<string>();
  walk(root, (node) => {
    if (!wanted.has(node.id)) return;
    const label = node.name ?? (node.type === "text" ? node.text : undefined) ?? "section";
    const base = label.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 40) || "section";
    let id = base;
    for (let i = 2; taken.has(id); i++) id = `${base}-${i}`;
    taken.add(id);
    ids.set(node.id, id);
  });
  return ids;
}

/** Properties a component's own elements switch (they become state). */
export function switchedProps(root: DesignNode): Set<string> {
  const props = new Set<string>();
  walk(root, (node) => {
    if (node.interaction?.type === "variant") props.add(node.interaction.prop);
  });
  return props;
}

/** `export const testimonials = [ … ];` */
export function dataModule(
  name: string,
  label: string,
  items: readonly Record<string, JsonValue>[],
  value: (key: string, v: JsonValue) => JsonValue,
  /** Icons named in the data: the map from those names to lucide's components (`<name>Icons`). */
  icons?: { map: string; names: readonly { name: string; component: string }[] },
): string {
  const rows = items.map((item) => `  { ${Object.entries(item).map(([k, v]) => `${/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k)}: ${JSON.stringify(value(k, v))}`).join(", ")} },`);
  const doc = `/** ${label.replace(/\*\//g, "")}: sample data from the design (generated by AppShape; edit freely). */\nexport const ${name} = [\n${rows.join("\n")}\n];\n`;
  if (!icons?.names.length) return doc;
  const components = [...new Set(icons.names.map((n) => n.component))].sort();
  const entries = icons.names.map((n) => `  ${JSON.stringify(n.name)}: ${n.component},`);
  return `import { ${components.join(", ")} } from "lucide-react";\n\n${doc}\n/** The icons the data names (add one here when the data names a new one). */\nexport const ${icons.map} = {\n${entries.join("\n")}\n};\n`;
}
